// Builds js/data.js from the UCI SMS Spam Collection (CC BY 4.0).
// Usage: node tools/build-data.js
const fs = require("fs");
const path = require("path");

const raw = fs.readFileSync(path.join(__dirname, "SMSSpamCollection"), "utf8");
const seen = new Set();
const corpus = [];

for (const line of raw.split("\n")) {
  const m = line.match(/^(ham|spam)\t(.*)$/);
  if (!m) continue;
  const text = m[2].trim();
  if (text.length < 12) continue; // drop unusably short lines
  const key = text.toLowerCase().replace(/\s+/g, " ");
  if (seen.has(key)) continue; // dedupe (repeated ham chatter)
  seen.add(key);
  corpus.push([text, m[1] === "spam" ? 1 : 0]);
}

const nSpam = corpus.filter((c) => c[1] === 1).length;
const out = `// Generated by tools/build-data.js — do not edit.
// Source: UCI Machine Learning Repository — SMS Spam Collection (Almeida, Hidalgo, Yamakami, 2011).
// License: Creative Commons CC BY 4.0. https://archive.ics.uci.edu/dataset/228/sms+spam+collection
(typeof window !== "undefined" ? window : globalThis).SCAMPROOF_META = {
  n: ${corpus.length},
  nSpam: ${nSpam},
  nHam: ${corpus.length - nSpam},
  source: "UCI Machine Learning Repository — SMS Spam Collection",
  citation: "Almeida, T.A., Hidalgo, J.M.G., Yamakami, A. (2011). Contributions to the study of SMS spam filtering.",
  license: "CC BY 4.0",
  url: "https://archive.ics.uci.edu/dataset/228/sms+spam+collection"
};
(typeof window !== "undefined" ? window : globalThis).SCAMPROOF_CORPUS = ${JSON.stringify(corpus)};
`;
fs.mkdirSync(path.join(__dirname, "..", "js"), { recursive: true });
fs.writeFileSync(path.join(__dirname, "..", "js", "data.js"), out);
console.log(`Wrote js/data.js with ${corpus.length} messages (${nSpam} spam, ${corpus.length - nSpam} ham)`);
